export function makeT(lang: Lang) {
  return (key: string, vars?: Record<string, string | number>): string => {
    const e = S[key]
    let s = e ? (e[lang] ?? e.en) : key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    }
    return s
  }
}
